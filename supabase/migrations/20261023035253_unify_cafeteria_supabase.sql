-- Preserve the existing cafeteria history and extend the same table.
create table if not exists public.cafeteria (
    id bigint generated by default as identity primary key,
    created_at timestamptz default now(),
    people integer default 0,
    status text default '空いている',
    predict10 integer default 0,
    predict20 integer default 0,
    updated_at timestamptz default now(),
    occupancy integer default 0,
    notice text default '',
    curry boolean default true,
    ramen boolean default true,
    karaage boolean default false,
    daily boolean default true
);

do $$
begin
    if not exists (select 1 from pg_constraint
        where conrelid = 'public.cafeteria'::regclass and contype = 'p') then
        alter table public.cafeteria add constraint cafeteria_pkey primary key (id);
    end if;
end $$;

alter table public.cafeteria add column if not exists status_icon text;
update public.cafeteria
set status_icon = case when occupancy < 30 then '🟢' when occupancy < 70 then '🟡' else '🔴' end
where status_icon is null;
alter table public.cafeteria alter column status_icon set default '⚪';
alter table public.cafeteria alter column status_icon set not null;



alter table public.cafeteria add constraint cafeteria_people_nonnegative check (people >= 0);
alter table public.cafeteria add constraint cafeteria_occupancy_nonnegative check (occupancy >= 0);
alter table public.cafeteria add constraint cafeteria_predictions_nonnegative check (predict10 >= 0 and predict20 >= 0);
alter table public.cafeteria add constraint cafeteria_notice_length check (char_length(notice) <= 2000);
create index cafeteria_latest_idx on public.cafeteria (updated_at desc nulls last, id desc);

create table public.cafeteria_admins (
    user_id uuid primary key references auth.users(id) on delete cascade,
    created_at timestamptz not null default now()
);
alter table public.cafeteria_admins enable row level security;
revoke all on public.cafeteria_admins from public, anon, authenticated;
grant select on public.cafeteria_admins to authenticated;
grant all on public.cafeteria_admins to service_role;
create policy cafeteria_admins_read_self on public.cafeteria_admins
    for select to authenticated using (user_id = (select auth.uid()));

alter table public.cafeteria enable row level security;
revoke all on public.cafeteria from public, anon, authenticated;
grant select on public.cafeteria to anon, authenticated;
grant insert on public.cafeteria to authenticated;
grant all on public.cafeteria to service_role;
-- Identity values are generated by the database when the admin app inserts history.
grant usage on sequence public.cafeteria_id_seq to authenticated, service_role;
drop policy if exists "Allow public read cafeteria" on public.cafeteria;
create policy cafeteria_public_read on public.cafeteria
    for select to anon, authenticated using (true);
create policy cafeteria_admin_insert on public.cafeteria
    for insert to authenticated with check (
        exists (select 1 from public.cafeteria_admins where user_id = (select auth.uid()))
    );

create function public.stamp_cafeteria_updated_at()
returns trigger language plpgsql security invoker set search_path = ''
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;
revoke all on function public.stamp_cafeteria_updated_at() from public, anon, authenticated;
create trigger cafeteria_set_updated_at
    before insert or update on public.cafeteria
    for each row execute function public.stamp_cafeteria_updated_at();

do $$
begin
    if not exists (select 1 from pg_publication_tables
        where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'cafeteria') then
        alter publication supabase_realtime add table public.cafeteria;
    end if;
end $$;

notify pgrst, 'reload schema';
